"""Bundled crash-window moves (Kraken public trade history) for the replays.

`crash_history.json` is regenerated by `scripts/fetch_crash_history.py`; it is
static history, so shipping it keeps the replays offline and reproducible.
"""

from __future__ import annotations

import json
from functools import cache
from importlib import resources

from cqd.engine.stress import CrashWindow


@cache
def load_crash_windows() -> tuple[CrashWindow, ...]:
    raw = json.loads(resources.files("cqd.data").joinpath("crash_history.json").read_text())
    return tuple(
        CrashWindow(
            key=w["key"],
            label=w["label"],
            start=w["start"],
            end=w["end"],
            note=w.get("note", ""),
            moves={a: float(m["return"]) for a, m in w["assets"].items()},
        )
        for w in raw["windows"]
    )
